#!/usr/bin/env python3
"""Generate data.js (the worker's lookup tables) from the bank's test-customers.json.

Usage:
  python3 -I build_data.py [path/to/test-customers.json] [path/to/data.js]

Each entry becomes {http, body, delaySeconds?}: `body` is the response
pre-serialized as a JSON string (Python keeps 0.0 as 0.0), so the mock returns
exactly the bodies and status codes listed in the test file.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.join(
    HERE, "..", "..", "Build the Builder - Final Case", "test-environment", "test-customers.json"
)

CUSTOMER_SERVICES = {"cards.list", "contact.email.get", "statement.pdf.send"}
CARD_SERVICES = {"cards.balance", "statement.week.get"}
CARD_WEEK_SERVICES = {"statement.week.decide", "statement.week.change"}


def prep(entry):
    out = {"http": entry["http"], "body": json.dumps(entry["response"], ensure_ascii=False, separators=(",", ":"))}
    if "delaySeconds" in entry:
        out["delaySeconds"] = entry["delaySeconds"]
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "data.js")
    with open(src, encoding="utf-8") as f:
        doc = json.load(f)

    customers = {}  # customerNo -> {service: entry}
    cards = {}  # cardNumber -> {service: entry | {week: entry}}
    for cu in doc["customers"]:
        cno = str(cu["customerNo"]).strip()
        cust = customers.setdefault(cno, {})
        for svc, val in cu["services"].items():
            if svc in CUSTOMER_SERVICES:
                cust[svc] = prep(val)
            elif svc in CARD_SERVICES or svc in CARD_WEEK_SERVICES:
                for card, entry in val.items():
                    if card in cards and svc in cards[card]:
                        raise SystemExit(f"duplicate card {card} for {svc}")
                    cards.setdefault(card, {})[svc] = (
                        {str(w): prep(e) for w, e in entry.items()} if svc in CARD_WEEK_SERVICES else prep(entry)
                    )
            else:
                raise SystemExit(f"unknown service {svc}")

    out = (
        "// GENERATED by build_data.py from test-customers.json. Do not edit by hand.\n"
        "export const CUSTOMERS = " + json.dumps(customers, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "export const CARDS = " + json.dumps(cards, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )
    with open(dst, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {dst}: {len(customers)} customers, {len(cards)} cards, {len(out.encode())} bytes")


if __name__ == "__main__":
    main()
